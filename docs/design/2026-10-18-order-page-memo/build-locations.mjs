// Builds locations.js for the prototype: districts + upazilas + city thanas.
//   node docs/design/2026-10-18-order-page-v2/build-locations.mjs
//
// Base: the 64 districts / 494 upazilas already pinned in Merchant-Suite
//   (sera-khabar-commerceos/server/risk/dictionaries/bdLocations.json, from MIT nuhil/bangladesh-geocode).
// Added: the 102 city/thana records (ids 495-596) from MIT imran110219/geo-vault, pinned below,
//   with the source errors corrected and the missing DMP thanas added.
import { readFile, writeFile } from "node:fs/promises";

const GEO_VAULT_COMMIT = "94a7b3999f46a34532bafe6480badd152fe8b808";
const GEO_VAULT_URL = `https://raw.githubusercontent.com/imran110219/geo-vault/${GEO_VAULT_COMMIT}/data/countries/bd/formats/upazilas/upazilas.json`;
const base = JSON.parse(await readFile(new URL("../../../../sera-khabar-commerceos/server/risk/dictionaries/bdLocations.json", import.meta.url), "utf8"));
const vault = (await (await fetch(GEO_VAULT_URL)).json()).find((entry) => entry.type === "table").data;

const nfc = (value) => value.normalize("NFC").trim();
const dhaka = base.districts.find((district) => district.name === "Dhaka").id;

// Corrections to geo-vault's city records, by id. `null` drops the record.
const fixes = {
  Wari: { district_id: dhaka },                      // listed under Munshiganj; Wari is a DMP thana
  Demark: { name: "Demra" },                         // typo
  "Tongu East": { name: "Tongi East" },              // typo
  Hajiratat: { name: "Hajirhat" },                   // typo
  Karnaher: { name: "Karnahar" },                    // typo
  "Biman Bandar": { name: "Airport" },
  Chandgaon: { bn_name: "চান্দগাঁও" },                // "চাঁান্দগাঁও" in source
  Gazerpara: null,                                   // not an SMP thana; Bangla said "গাজীপুর"
};
// DMP thanas missing from the source.
const additions = [
  ["Banani", "বনানী"], ["Dakshinkhan", "দক্ষিণখান"], ["Uttarkhan", "উত্তরখান"],
  ["Mugda", "মুগদা"], ["Shahjahanpur", "শাহজাহানপুর"],
].map(([name, bn_name], index) => ({ id: `x${index + 1}`, district_id: dhaka, name, bn_name }));

const city = [];
for (const record of vault.filter((row) => row.is_city === "true")) {
  const key = Object.keys(fixes).find((name) => record.name === name || (name === "Chandgaon" && record.bn_name.includes("চাঁান্দ")));
  if (key && fixes[key] === null) continue;
  city.push({ ...record, ...(key ? fixes[key] : {}) });
}
city.push(...additions);

const districts = base.districts.map((district) => [district.id, nfc(district.bnName), district.name, nfc(base.divisions.find((division) => division.id === district.divisionId).bnName)]);
const upazilas = base.upazilas.map((upazila) => [upazila.id, upazila.districtId, nfc(upazila.bnName), upazila.name, 0]);
const seen = new Set(upazilas.map(([, districtId, bn]) => `${districtId}:${bn}`));
// A city thana with the same name as an upazila of its district (e.g. দক্ষিণ সুরমা) is one choice for a customer.
const cityThanas = city.map((record) => [String(record.id), String(record.district_id), nfc(record.bn_name), record.name, 1]).filter(([, districtId, bn]) => !seen.has(`${districtId}:${bn}`));
const thanas = [...upazilas, ...cityThanas];

const banner = `// Generated by build-locations.mjs. Do not edit by hand.
// 64 districts, ${base.upazilas.length} upazilas (Merchant-Suite bdLocations.json, MIT nuhil/bangladesh-geocode)
// + ${cityThanas.length} city thanas (MIT imran110219/geo-vault@${GEO_VAULT_COMMIT.slice(0, 7)}, corrected).
// districts: [id, bn, en, divisionBn]   thanas: [id, districtId, bn, en, isCityThana]
`;
await writeFile(new URL("./locations.js", import.meta.url), `${banner}export const DISTRICTS = ${JSON.stringify(districts)};\nexport const THANAS = ${JSON.stringify(thanas)};\n`);
console.log(`districts ${districts.length}, thanas ${thanas.length} (city ${cityThanas.length})`);
